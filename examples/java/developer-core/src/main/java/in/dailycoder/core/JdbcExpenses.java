package in.dailycoder.core;

import javax.sql.DataSource;
import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.SQLException;
import java.sql.Statement;
import java.sql.Date;
import java.util.ArrayList;
import java.util.List;

public final class JdbcExpenses implements ExpenseRepository {
    private final DataSource source;
    public JdbcExpenses(DataSource source) throws SQLException {
        this.source = source;
        try (var connection = source.getConnection(); var statement = connection.createStatement()) {
            statement.execute("CREATE TABLE IF NOT EXISTS expenses (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, label VARCHAR(100) NOT NULL, amount INTEGER NOT NULL CHECK (amount > 0), spent_on DATE NOT NULL)");
        }
    }
    private Expense insert(Connection connection, Expense value) throws SQLException {
        try (PreparedStatement statement = connection.prepareStatement("INSERT INTO expenses(label, amount, spent_on) VALUES (?, ?, ?)", Statement.RETURN_GENERATED_KEYS)) {
            statement.setString(1, value.label()); statement.setInt(2, value.amount());
            statement.setDate(3, Date.valueOf(value.date())); statement.executeUpdate();
            try (var keys = statement.getGeneratedKeys()) {
                if (!keys.next()) throw new SQLException("Insert did not return an id");
                return new Expense(keys.getLong(1), value.label(), value.amount(), value.date());
            }
        }
    }
    public Expense add(Expense value) throws SQLException {
        try (var connection = source.getConnection()) { return insert(connection, value); }
    }
    public void addAll(List<Expense> values) throws SQLException {
        try (var connection = source.getConnection()) {
            connection.setAutoCommit(false);
            try {
                for (Expense value : values) insert(connection, value);
                connection.commit();
            } catch (SQLException | RuntimeException error) {
                try { connection.rollback(); } catch (SQLException rollback) { error.addSuppressed(rollback); }
                throw error;
            }
        }
    }
    public List<Expense> list() throws SQLException {
        var result = new ArrayList<Expense>();
        try (var connection = source.getConnection(); var statement = connection.prepareStatement("SELECT id, label, amount, spent_on FROM expenses ORDER BY id"); var rows = statement.executeQuery()) {
            while (rows.next()) result.add(new Expense(rows.getLong("id"), rows.getString("label"), rows.getInt("amount"), rows.getDate("spent_on").toLocalDate()));
        }
        return List.copyOf(result);
    }
    public List<Expense> findAtLeast(int minimum) throws SQLException {
        var result = new ArrayList<Expense>();
        try (var connection = source.getConnection(); var statement = connection.prepareStatement("SELECT id, label, amount, spent_on FROM expenses WHERE amount >= ? ORDER BY id")) {
            statement.setInt(1, minimum);
            try (var rows = statement.executeQuery()) {
                while (rows.next()) result.add(new Expense(rows.getLong("id"), rows.getString("label"), rows.getInt("amount"), rows.getDate("spent_on").toLocalDate()));
            }
        }
        return List.copyOf(result);
    }
}
